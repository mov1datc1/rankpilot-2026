import { createHash } from 'node:crypto';

// Template changes invalidate artifact approval, not source selection or saved prose.
import { RENDERER_VERSION, ARTIFACT_REVIEW_VERSION } from './review-versions';
export { RENDERER_VERSION, ARTIFACT_REVIEW_VERSION } from './review-versions';

function stable(value: any): any {
  if (value instanceof Date) return value.toISOString();
  if (Array.isArray(value)) return value.map(stable);
  if (value && typeof value === 'object') return Object.fromEntries(Object.keys(value).sort().map(k => [k, stable(value[k])]));
  return value;
}
/** Bind approval to all editorial inputs, excluding the approval and generated bytes themselves. */
export function deliveryInputHash(submission: any, data: any = submission.chambersData || {}) {
  const {available_artifact, approved_artifact, previous_approved_artifact, release_verdict, cloned_docx_b64, review_checkpoint, ...inputs} = data;
  return createHash('sha256').update(JSON.stringify(stable({rendererVersion:RENDERER_VERSION,artifactReviewVersion:ARTIFACT_REVIEW_VERSION,practiceArea:submission.practiceArea, targetDirectory:submission.targetDirectory, guideRegion:submission.guideRegion, currentBand:submission.currentBand, inputs}))).digest('hex');
}
export function artifactHash(buffer: Buffer) { return createHash('sha256').update(buffer).digest('hex'); }

/** Preserve only bytes that were approved against the exact pre-edit inputs. */
export function previousApprovedArtifact(submission:any,data:any) {
  const pair=data.approved_artifact;
  if(data.release_verdict?.passed && pair?.input_hash===deliveryInputHash(submission,data)
    && pair?.base64 && pair?.audit_base64
    && artifactHash(Buffer.from(pair.base64,'base64'))===pair.sha256
    && artifactHash(Buffer.from(pair.audit_base64,'base64'))===pair.audit_sha256) {
    return {...pair,archived_at:new Date().toISOString()};
  }
  return data.previous_approved_artifact || null;
}

/** Draft bytes have their own binding; they never confer editorial approval. */
export function draftInputHash(submission:any,data:any=submission.chambersData || {}) {
  // Resetting a review cache marker starts a repair; it does not edit the
  // candidate documents. All source and generated content remains bound.
  const {draft_artifact,completed_review_input_hash,...inputs}=data;
  return deliveryInputHash(submission,inputs);
}
export function storedDraftBytes(submission:any,data:any,kind:string):Buffer|null {
  const draft=data.draft_artifact;
  if(!draft) return null;
  const current=draftInputHash(submission,data);
  // Legacy drafts included this cache marker. Accept only the exact old
  // binding reconstructed from their own revision, never changed content.
  const {draft_artifact,...legacyInputs}=data;
  const legacy=deliveryInputHash(submission,legacyInputs);
  const resetLegacy=data.completed_review_input_hash===null && typeof draft.revision_id==='string'
    ? deliveryInputHash(submission,{...legacyInputs,completed_review_input_hash:draft.revision_id}) : null;
  if(![current,legacy,resetLegacy].includes(draft.input_hash)) return null;
  const encoded=kind==='submission'?draft.base64:kind==='audit'?draft.audit_base64:null;
  const expected=kind==='submission'?draft.sha256:draft.audit_sha256;
  if(!encoded || !expected) return null;
  const bytes=Buffer.from(encoded,'base64');
  if(artifactHash(bytes)!==expected) throw new Error('DRAFT_ARTIFACT_CORRUPTED');
  return bytes;
}

/** Availability is not approval. Download only the complete pair bound to the
 * current inputs, never rerender or label unreviewed bytes as approved. */
export function storedAvailableBytes(submission:any,data:any,kind:string):Buffer|null {
  const pair=data.available_artifact || data.approved_artifact;
  if(!pair && data.draft_artifact) {
    // Historical assembled pairs retain their own exact-input binding.
    const submissionBytes=storedDraftBytes(submission,data,'submission');
    const auditBytes=storedDraftBytes(submission,data,'audit');
    return submissionBytes && auditBytes ? (kind==='submission'?submissionBytes:kind==='audit'?auditBytes:null):null;
  }
  if(!pair || !pair.base64 || !pair.audit_base64 || pair.input_hash!==deliveryInputHash(submission,data))return null;
  if(!['submission','audit'].includes(kind))return null;
  for(const [encoded,expected] of [[pair.base64,pair.sha256],[pair.audit_base64,pair.audit_sha256]]) {
    if(artifactHash(Buffer.from(encoded,'base64'))!==expected)throw new Error('AVAILABLE_ARTIFACT_CORRUPTED');
  }
  return Buffer.from(kind==='submission'?pair.base64:pair.audit_base64,'base64');
}
